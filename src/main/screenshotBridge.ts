import { createServer } from "node:http";
import { randomUUID } from "node:crypto";
import { mkdir, writeFile, rm } from "node:fs/promises";
import { join } from "node:path";

export type CaptureRequest = { url: string; width: number; height: number };
export function captureRequest(input: unknown): CaptureRequest {
  const value = input as Partial<CaptureRequest> | null;
  if (!value || typeof value.url !== "string") throw new Error("A URL is required");
  const url = new URL(value.url);
  if (!["http:", "https:", "file:"].includes(url.protocol)) throw new Error("Use an http, https, or file URL");
  const width = value.width ?? 1440, height = value.height ?? 900;
  if (![width, height].every(n => Number.isInteger(n) && n >= 100 && n <= 4096)) throw new Error("Viewport dimensions must be integers from 100 to 4096");
  return { url: url.href, width, height };
}

export async function startScreenshotBridge(cwd: string, capture: (request: CaptureRequest) => Promise<string>) {
  const token = randomUUID();
  let busy = false;
  const server = createServer(async (req, res) => {
    res.setHeader("Content-Type", "application/json");
    if (req.headers.authorization !== `Bearer ${token}` || req.headers.origin) {
      res.writeHead(403).end(JSON.stringify({ error: "Forbidden" })); return;
    }
    if (req.method !== "POST" || req.url !== "/screenshot") {
      res.writeHead(404).end(JSON.stringify({ error: "Not found" })); return;
    }
    if (busy) { res.writeHead(409).end(JSON.stringify({ error: "A capture is already running" })); return; }
    busy = true;
    try {
      let body = "";
      for await (const chunk of req) {
        body += chunk;
        if (body.length > 16_384) throw new Error("Request too large");
      }
      const path = await capture(captureRequest(JSON.parse(body)));
      res.end(JSON.stringify({ path }));
    } catch (error) {
      res.writeHead(400).end(JSON.stringify({ error: (error as Error).message }));
    } finally { busy = false; }
  });
  server.requestTimeout = 35_000;
  await new Promise<void>((resolve, reject) => { server.once("error", reject); server.listen(0, "127.0.0.1", resolve); });
  const port = (server.address() as { port: number }).port;
  const dir = join(cwd, ".consort", "tools");
  const helper = join(dir, `screenshot-${token}.cjs`);
  const close = async () => {
    server.closeAllConnections();
    await new Promise<void>((resolve) => server.close(() => resolve()));
    await rm(helper, { force: true });
  };
  try {
    await mkdir(dir, { recursive: true });
    await writeFile(helper, `// Generated by Consort; valid only for the current agent turn.\n(async () => {\n  const [url, width, height] = process.argv.slice(2);\n  if (!url) throw new Error('Usage: node screenshot.cjs URL [width height]');\n  const response = await fetch('http://127.0.0.1:${port}/screenshot', { method: 'POST', headers: { Authorization: 'Bearer ${token}', 'Content-Type': 'application/json' }, body: JSON.stringify({ url, ...(width ? { width: Number(width) } : {}), ...(height ? { height: Number(height) } : {}) }), signal: AbortSignal.timeout(35000) });\n  const result = await response.json();\n  if (!response.ok) throw new Error(result.error);\n  console.log(result.path);\n})().catch(error => { console.error(error.message); process.exitCode = 1; });\n`, { mode: 0o600 });
  } catch (error) { await close(); throw error; }
  const command = `node '${helper.replaceAll("'", "'\\''")}'`;
  return { helper, close, prompt: `You can run code, tests, and development servers using your built-in shell tool in this worktree.\nTo take a browser screenshot, run: ${command} 'http://localhost:3000' [width height]\nReplace the URL with the page to capture (http, https, or file URL). The optional viewport defaults to 1440 by 900. Start any needed dev server first. This uses an isolated browser and saves a PNG under .consort/screenshots; the command prints its absolute path. Read the PNG with your image/file tool to inspect it, then link it in your response using Markdown. The helper is valid only for this turn; use this exact helper rather than one from an earlier turn. Screenshots capture a viewport after page load and fonts settle; they do not capture the desktop or an existing signed-in browser. The PHI restrictions also apply to screenshots and code execution.` };
}
